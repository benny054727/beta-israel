/** בונה כתובת פנימית באתר, בהתחשב בתיקיית הבסיס של GitHub Pages */
export function url(path = '/'): string {
  const base = import.meta.env.BASE_URL.replace(/\/$/, '');
  const clean = path.replace(/^\//, '');
  return `${base}/${clean}`;
}

